  data=await getData()
  assert.equal(data.ops.stock["RM-001"],beforeStock+12,"Posted stock persists after reloading the React app")
  assert.equal(data.modules.batches.filter(r=>r.incoming===rec.id).length,1,"Receipt batch survives reload")
  await asEmployee("E009")
  await navigate("warehouse","warehouseIncoming")
  assert.equal(await page.locator(`[data-proc-action="storeReceipt"][data-proc-id="${rec.id}"]`).count(),0,"Cannot store twice")
