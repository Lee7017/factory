  await board.locator('.proc-order-search').fill("NO-MATCH-PURCHASE")
  assert.equal(await board.locator('.proc-order-row:visible').count(),0)
  await board.locator('.proc-order-search').fill("")
  assert.equal(await board.locator('.proc-order-row:visible').count(),1)
  assert.equal(await board.locator('.proc-order-table td').filter({hasText:"SO-"}).count(),0,
    "Purchase workbench cannot display sales order IDs as business rows")
  await page.screenshot({path:"test-results/purchase-toolbar-desktop.png",fullPage:false})
  // Sales has its own page and must not contain procurement fields or actions.
  await asEmployee("E013")
  await navigate("sales","orders")
  assert.equal(await page.locator('.native-business .proc-purchase-board').count(),0)
  assert.equal(await page.locator('.native-business [data-proc-action="newPurchase"]').count(),0)
  await page.screenshot({path:"test-results/purchase-sales-are-separate.png"})
  await asEmployee("E014")
  await navigate("purchase","purchase")
  // Old purchase records without independent demand authorization are blocked.
  let data=await getData()
  assert.equal(data.ops.purchases.find(x=>x.id==="PO-001")?.status,"待补采购需求")
  assert.equal(await page.locator('[data-proc-action="approve"][data-proc-id="PO-001"]').count(),0)
  await asEmployee("E007")
  await navigate("pmc","kitting")
  await page.locator('[data-proc-action="newRequest"]').click()
  let form=page.locator("#proc-form")
  await form.locator('[name="material"]').selectOption("RM-001")
  await form.locator('[name="qty"]').fill("12")
  await form.locator('[name="reason"]').fill("生产计划安全库存补货")
  await form.locator('button[type="submit"]').click()
  data=await getData()
  const demand=data.ops.purchaseRequests.find(x=>x.material==="RM-001"&&x.qty===12)
  assert.ok(demand&&demand.createdBy==="E007"&&demand.status==="待PMC确认")
  assert.equal(await page.locator(`[data-proc-action="approveRequest"][data-proc-id="${demand.id}"]`).count(),0,"PMC submitter cannot approve own demand")
  await page.screenshot({path:"test-results/purchase-01-pmc-demand.png"})
  await asEmployee("E022")
  await navigate("pmc","kitting")
  await page.locator(`[data-proc-action="approveRequest"][data-proc-id="${demand.id}"]`).click()
  assert.equal((await getData()).ops.purchaseRequests.find(x=>x.id===demand.id).status,"已确认")
  await asEmployee("E014")
  await navigate("purchase","purchase")
  await page.locator('[data-proc-action="newPurchase"]').click()
  form=page.locator("#proc-form")
  await form.locator('[name="requestId"]').selectOption(demand.id)
  await form.locator('[name="supplier"]').fill("测试供应商")
  await form.locator('[name="unitPrice"]').fill("12.5")
  await form.locator('button[type="submit"]').click()
  data=await getData()
  const record=data.ops.purchases.find(x=>x.requestId===demand.id)
  assert.ok(record)
  assert.equal(record.qty,12)
  assert.equal(record.totalAmount,150)
  assert.equal(record.status,"待采购主管审批")
  assert.deepEqual([record.approvalPlan.finance,record.approvalPlan.leadership],[true,true],"Unconfigured budget and new vendor trigger extra reviews")
  const poId=record.id
  assert.equal(await page.locator(`[data-proc-action="approve"][data-proc-id="${poId}"]`).count(),0,"PO creator cannot approve")
  await page.screenshot({path:"test-results/purchase-02-priced-po.png"})
  await asEmployee("E009")
  await navigate("warehouse","warehouseIncoming")
  assert.equal(await page.locator(`[data-proc-action="newReceipt"][data-proc-id="${poId}"]`).count(),0,"Unapproved PO is not receivable")
  await asEmployee("E021")
  await navigate("purchase","purchase")
  await page.locator(`[data-proc-action="approve"][data-proc-id="${poId}"]`).click()
  assert.equal((await getData()).ops.purchases.find(x=>x.id===poId).status,"待财务审核")
  await page.evaluate(()=>window.FactoryFlowUI?.dismiss?.())
  await asEmployee("E016")
  await navigate("finance","finance")
  await page.locator(`[data-proc-action="approveFinance"][data-proc-id="${poId}"]`).click()
  assert.equal((await getData()).ops.purchases.find(x=>x.id===poId).status,"待总经办审批")
  await page.evaluate(()=>window.FactoryFlowUI?.dismiss?.())
  await page.screenshot({path:"test-results/purchase-03-finance.png"})
  await asEmployee("E018")
  await navigate("leadership","approvals")
  await page.locator(`[data-proc-action="approveLeadership"][data-proc-id="${poId}"]`).click()
  assert.equal((await getData()).ops.purchases.find(x=>x.id===poId).status,"待到货")
  await page.evaluate(()=>window.FactoryFlowUI?.dismiss?.())
  await page.screenshot({path:"test-results/purchase-04-leadership.png"})
  await asEmployee("E009")
  await navigate("warehouse","warehouseIncoming")
  const receive=page.locator(`[data-proc-action="newReceipt"][data-proc-id="${poId}"]`)
