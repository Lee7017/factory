  await asEmployee("E018")
  await navigate("leadership","approvals")
  await page.locator('[data-proc-action="editPolicy"]').click()
  form=page.locator("#proc-form")
  await form.locator('[name="financeLimit"]').fill("10000")
  await form.locator('[name="leadershipLimit"]').fill("100000")
  await form.locator('[name="budgetLimit"]').fill("100000")
  await form.locator('[name="approvedSuppliers"]').fill("合格供应商")
  await form.locator('button[type="submit"]').click()
  await asEmployee("E007")
  await navigate("pmc","kitting")
  await page.locator('[data-proc-action="newRequest"]').click()
  form=page.locator("#proc-form")
  await form.locator('[name="material"]').selectOption("PK-001")
  await form.locator('[name="qty"]').fill("20")
  await form.locator('[name="reason"]').fill("生产安全库存补货")
  await form.locator('button[type="submit"]').click()
  const approvedReq=(await getData()).ops.purchaseRequests.find(x=>x.material==="PK-001"&&x.qty===20)
  await asEmployee("E022")
  await navigate("pmc","kitting")
  await page.locator(`[data-proc-action="approveRequest"][data-proc-id="${approvedReq.id}"]`).click()
  await asEmployee("E014")
